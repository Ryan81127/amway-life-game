function dictPair(en) {
  const key = plainKey(en);
  const tw = EXTRA_TW[key] || (typeof PLAYER_ZH === "object" ? PLAYER_ZH[key] : "");
  if (!tw) return null;
  const cn = NAME_CN[key] || (typeof han === "function" ? han(tw) : tw);
  return { tw, cn };
}
